    /** Rows ready for BirthdayMessage::create / SQL (without category_id). */
    public static function rows(): array
    {
        $rows = [];
        foreach (self::WISHES as $relationship => $items) {
            $n = [];
            foreach ($items as [$tone, $body]) {
                $lang = preg_match('/\p{Arabic}/u', $body) ? 'ur' : 'en';
                $key = $tone.($lang === 'ur' ? '-ur' : '');
                $n[$key] = ($n[$key] ?? 0) + 1;
                $rows[] = [
                    'relationship' => $relationship,
                    'tone' => $tone,
                    'language' => $lang,
                    'body' => $body,
                    'slug' => sprintf('bw-%s-%s-%02d', str_replace('_', '-', $relationship), $key, $n[$key]),
                ];
            }
        }

        return $rows;
    }
